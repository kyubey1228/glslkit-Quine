raise "expected 95 glyphs, got #{GLYPHS.size}" unless GLYPHS.size == 95
GLYPHS.each_with_index do |rows, i|
  raise "glyph #{i}: bad shape" unless rows.size == 6 && rows.all? { _1.size == 5 }
end

FONT_WORDS = GLYPHS.map do |rows|
  rows.each_with_index.sum do |row, r|
    row.chars.each_with_index.sum { |ch, c| (ch == "#") ? 1 << (r * 5 + c) : 0 }
  end
end

FONT_HEX = FONT_WORDS.map { format("%08x", _1) }.join

